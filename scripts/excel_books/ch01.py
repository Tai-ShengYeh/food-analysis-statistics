"""Ch01 統計入門：平均數、標準差、變異係數與相對誤差。

R 的答案來源：Rscript R/ch01_basics.R（水分 4 次測定 Nielsen Table 4.1 + 乾物質習題）。
"""
from excel_common import Book


def build():
    book = Book("ch01_basics_stats.xlsx",
                 "Ch1 統計入門：平均數、標準差、變異係數與相對誤差", "ch01.html")
    book.readme([
        "# 這本活頁簿在做什麼",
        "生漢堡肉水分測了 4 次（Nielsen Table 4.1：64.53、64.45、65.10、64.78%）。"
        "「描述統計」工作表一步一步算出報告要寫的『一個共識值 ＋ 一個散布程度』：平均數、中位數、標準差 SD、變異係數 CV%。",
        "「準確度與相對誤差」工作表示範：如果已知真值（例如標準品 65.05%），怎麼算絕對誤差 Eabs 與相對誤差 %Erel。",
        "「乾物質習題」工作表用同一套公式練習 Nielsen 章末習題的數據，其中一筆數字（82.20）看起來特別低——"
        "先別急著判斷是不是異常值，第 5 章會教你用 Dixon Q 檢定客觀判斷能不能剔除。",
        "# 怎麼用",
        "1.「描述統計」：左邊黃色是原始數據，右邊每一列是一個公式，C 欄會印出公式原文給你對照。",
        "2. 把黃色的水分數據改成你自己實驗的 3–5 次重複測定，所有結果會自動重算。",
        "3.「準確度與相對誤差」：把黃色的『真值』改一改，看 Eabs、%Erel 怎麼跟著變、正負號怎麼變。",
        "4.「乾物質習題」：練習同一套公式，同時觀察 82.20 這筆數字對平均與 SD 的影響有多大。",
        "5.「對照R答案」工作表會核對 Excel 算出來的與 R 的答案是否一致。",
        "# 用 Excel 資料分析工具箱算敘述統計（選用，不是必需）",
        "啟用方式：檔案 → 選項 → 增益集 → 下拉選『Excel 增益集』→ 執行 → 勾選『分析工具箱』→ 確定。"
        "之後『資料』分頁最右邊會多一個『資料分析』按鈕。",
        "操作：點『資料分析』→ 選『敘述統計』→ 輸入範圍框選水分 4 個數字（例如 A2:A5）→ 勾選『類別軸標記位於第一列』"
        "（如果框到標題）與『摘要統計』→ 指定輸出範圍 → 確定。",
        "對照：輸出表的『平均值』＝ R 的 mean()／Excel 的 AVERAGE；『標準差』＝ sd()／STDEV（工具箱內部也是用 n−1，"
        "與本活頁簿一致）；『中間值』＝ median()／MEDIAN；『範圍』＝全距（最大−最小）。",
        "⚠️ 工具箱輸出是『靜態的』快照——你改了原始數據，這張輸出表不會自動跟著變，要重新跑一次『資料分析』才會更新。"
        "本活頁簿「描述統計」工作表用的是活公式，數據一改，結果立刻自動重算，這是兩者最大的差別。",
        "# 本章最重要的觀念",
        "CV% ＝ SD ÷ 平均數 × 100，不是『平均 ÷ 標準差』——分子分母顛倒是最常見的錯。",
        "精密度好（SD、CV 小）不代表準確：要有已知真值（標準品、CRM）才能算 Eabs／%Erel、談準確度；"
        "相對誤差要用『真值』當分母，不是用測得值。",
    ])

    # ---- 描述統計：水分 4 次測定 -----------------------------------
    ws = book.sheet("描述統計", [20, 16, 44, 60])
    book.header(ws, 1, ["水分 (%)"])
    rng = book.data(ws, 2, 1, [64.53, 64.45, 65.10, 64.78], fmt="0.00")
    book.header(ws, 7, ["項目", "結果", "公式", "說明"])
    n = book.calc(ws, 8, "n（重複次數）", f"=COUNT({rng})", "數一數有幾個數據", fmt="0")
    mean = book.calc(ws, 9, "平均數 x̄", f"=AVERAGE({rng})", "報告要寫的『共識值』", key=True)
    median = book.calc(ws, 10, "中位數", f"=MEDIAN({rng})", "由小到大排中間的值，對極端值較不敏感")
    sd = book.calc(ws, 11, "標準差 SD", f"=STDEV.S({rng})", "數據彼此合不合群；分母是 n−1", key=True)
    cv = book.calc(ws, 12, "變異係數 CV%", f"={sd}/{mean}*100", "SD÷平均×100；不是平均÷SD！", key=True, fmt="0.000")
    book.calc(ws, 13, "全距 Range", f"=MAX({rng})-MIN({rng})", "最大−最小，只是參考用", fmt="0.00")
    book.text(ws, 15, 1, "報告寫法：64.72 ± 0.29 %（mean ± SD，n=4）；CV=0.45%，精密度良好（經驗法則 CV<5%）。", bold=True)

    # ---- 準確度與相對誤差 -------------------------------------------
    ws2 = book.sheet("準確度與相對誤差", [20, 16, 44, 60])
    book.header(ws2, 1, ["項目", "結果", "公式", "說明"])
    mean_link = book.calc(ws2, 2, "平均數 x̄（引用描述統計）", f"='描述統計'!{mean}", "與左表同一組水分數據")
    true_val = book.calc(ws2, 3, "真值 T（標準品）", 65.05, "可以改成你自己方法確效用的標準品真值", fmt="0.00")
    book.mark_input(ws2, true_val)
    eabs = book.calc(ws2, 4, "絕對誤差 Eabs", f"={mean_link}-{true_val}", "測得值−真值；負號＝結果偏低", key=True, fmt="0.000")
    erel = book.calc(ws2, 5, "相對誤差 %Erel", f"={eabs}/{true_val}*100", "Eabs÷真值×100（分母一定是真值，不是測得值）", key=True, fmt="0.000")
    book.text(ws2, 7, 1, "正負號要保留：−0.51% 代表結果偏低 0.51%，方向資訊很重要，不能只看絕對值。", bold=True)

    # ---- 乾物質習題 ---------------------------------------------------
    ws3 = book.sheet("乾物質習題", [20, 16, 44, 60])
    book.header(ws3, 1, ["乾物質 (%)"])
    rng3 = book.data(ws3, 2, 1, [88.62, 88.74, 89.20, 82.20], fmt="0.00")
    book.header(ws3, 7, ["項目", "結果", "公式", "說明"])
    n3 = book.calc(ws3, 8, "n（重複次數）", f"=COUNT({rng3})", fmt="0")
    mean3 = book.calc(ws3, 9, "平均數 x̄", f"=AVERAGE({rng3})", key=True)
    sd3 = book.calc(ws3, 10, "標準差 SD", f"=STDEV.S({rng3})", key=True)
    cv3 = book.calc(ws3, 11, "變異係數 CV%", f"={sd3}/{mean3}*100", "CV<5% 但 82.20 看起來特別低……", key=True, fmt="0.00")
    book.text(ws3, 13, 1,
              "82.20 是不是異常值？CV 看起來還算可以（<5%），但這是因為平均與 SD 都被它拖動了。"
              "先別急著刪——第 5 章的 Dixon Q 檢定會給你客觀的答案（劇透：可以捨棄，捨棄後 mean=88.85、SD=0.31）。",
              bold=True)

    # ---- 對照 R 答案 ---------------------------------------------------
    book.check("水分平均數 x̄", "描述統計", mean, 64.715)
    book.check("水分標準差 SD", "描述統計", sd, 0.292631736715844)
    book.check("水分變異係數 CV%", "描述統計", cv, 0.452185330627898)
    book.check("相對誤差 %Erel（真值65.05）", "準確度與相對誤差", erel, -0.514988470407369)
    book.check("乾物質平均數 x̄", "乾物質習題", mean3, 87.19)
    book.check("乾物質標準差 SD", "乾物質習題", sd3, 3.33604556323801)
    book.check("乾物質變異係數 CV%", "乾物質習題", cv3, 3.82617910682189)
    return book
